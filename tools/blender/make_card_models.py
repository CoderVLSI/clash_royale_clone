def T(m, R, r, x, y, z, rx=0, ry=0, rz=0):
    bpy.ops.mesh.primitive_torus_add(major_radius=R, minor_radius=r, location=(x, y, z), rotation=(rx, ry, rz), major_segments=24, minor_segments=8)
    return _finish(bpy.context.active_object, m, 'torus')

